"""The party panels under the minimap's location box (asked 2026-10-28 with a mockup and the user's asset zip
C:/Users/reo72/Downloads/TID_Craftopia_Party_UI_Assets.zip, copied into tools/assets/party/).

Writes:
- textures/cooptown/party/<part>.png: the user's pictures cropped to what is drawn and scaled down (PARTS).
- font/glyph_E2.png: the party's hidden marks (nearly see-through 1 px characters, like the map's tokens), on a
  page of their own so no glyph on E0 / E1 moves (adding marks there pushed item icons off the font before).
- tools/party-glyphs.json (for build-hud-log.mjs) and the BP's scripts/party-glyphs.js: mark name -> character.
Marks: pm<k> member k (1-3) is shown, pf<k>_<s> their face (PARTY_SKINS index), ph<k>_<n> their HP bar in tenths;
ns1 / ns2: a title banner's text drawn smaller (BP notify.js); bgm: the town music sign shows (BP town-bgm.js).
Run from the CoopTown_RP folder:  python -P tools/build-party-hud.py
"""
import json, os
from PIL import Image

RP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BP_SCRIPTS = os.path.join(RP, "..", "..", "development_behavior_packs", "CoopTown_BP", "scripts")
SRC = os.path.join(RP, "tools", "assets", "party")
OUT = os.path.join(RP, "textures", "cooptown", "party")
# picture -> width it is kept at (4 x its size on the HUD is plenty)
PARTS = {"member_panel": 416, "portrait_frame": 128, "title_ribbon": 256, "title_medal": 40, "heart": 32,
         "hp_track": 160, "hp_fill_green": 160, "hp_fill_red": 160}
# the job outfits' skins (textures/cooptown/skins), in the order of the pf marks; keep in step with party.js
PARTY_SKINS = ["traveler", "farmer", "fisher", "smith", "cook", "alchemist", "enchanter", "adventurer"]
MEMBERS, HP_STEPS = 3, 10
CELL_H = 12  # the map tokens' glyph height (tools/map_tiles.py CELL)

def marks():
    out = []
    for k in range(1, MEMBERS + 1):
        out.append("pm%d" % k)
        out += ["pf%d_%d" % (k, s) for s in range(len(PARTY_SKINS))]
        out += ["ph%d_%d" % (k, n) for n in range(HP_STEPS + 1)]
    # the title banners' smaller text sizes (BP notify.js fitBanner; added after the party's, so those keep their characters)
    out += ["ns1", "ns2"]
    # the town music is playing (BP town-bgm.js -> hud-info.js; RP build-hud-log.mjs bgmSign), added 2026-10-30
    out += ["bgm"]
    return out

def pictures():
    os.makedirs(OUT, exist_ok=True)
    for name, width in PARTS.items():
        im = Image.open(os.path.join(SRC, name + ".png")).convert("RGBA")
        im = im.crop(im.getbbox())
        im = im.resize((width, max(1, round(im.height * width / im.width))), Image.LANCZOS)
        im.save(os.path.join(OUT, name + ".png"))
        print("party", name, im.size)

def glyphs():
    page = Image.new("RGBA", (512, 512), (0, 0, 0, 0)); cell = 32
    token = Image.new("RGBA", (1, CELL_H), (0, 0, 0, 0)); token.putpixel((0, CELL_H // 2), (255, 255, 255, 4))
    table = {}
    for i, name in enumerate(marks(), start=1):  # cell 0 left empty, as on the other pages
        page.paste(token, ((i % 16) * cell, (i // 16) * cell + (cell - CELL_H) // 2))
        table["token:" + name] = chr(0xE200 + i)
    page.save(os.path.join(RP, "font", "glyph_E2.png"))
    json.dump(table, open(os.path.join(RP, "tools", "party-glyphs.json"), "w", encoding="utf8"), ensure_ascii=False, indent=1)
    with open(os.path.join(BP_SCRIPTS, "party-glyphs.js"), "w", encoding="utf8") as f:
        f.write("// Generated by CoopTown_RP/tools/build-party-hud.py. The party panels' hidden marks: name -> character.\n")
        f.write("export const PARTY_SKINS=%s;\n" % json.dumps(PARTY_SKINS))
        f.write("export const PARTY_GLYPHS=%s;\n" % json.dumps(table, indent=1))
    print("party marks:", len(table))

if __name__ == "__main__":
    pictures(); glyphs()
